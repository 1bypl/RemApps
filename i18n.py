_LANG = "pl"


def set_language(kod: str) -> None:
    global _LANG
    if kod in TRANSLATIONS:
        _LANG = kod


def language() -> str:
    return _LANG


def tr(klucz: str, **argumenty) -> str:
    tekst = TRANSLATIONS.get(_LANG, {}).get(klucz)
    if tekst is None:
        tekst = TRANSLATIONS["en"].get(klucz, klucz)
    if argumenty:
        try:
            return tekst.format(**argumenty)
        except (KeyError, IndexError, ValueError):
            return tekst
    return tekst
